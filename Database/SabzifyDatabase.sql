/* ---------------------------------------------------------------------------
   10. Orders
   OrderId is a STRING key today ("ORD001", "OR62051") with five mutually
   incompatible formats across the UI and no generator anywhere. The surrogate
   int PK fixes that while OrderNumber preserves the existing display ids.

   UserId is nullable because ownership is matched by email string today
   (Bill.aspx.cs:101-103 is the only check), and a legacy order may have no
   matching user row.

   DeliveryAddress stays as a flattened snapshot so an invoice reprints exactly
   as it was issued, even if the customer later edits the address it came from.
   --------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.Orders', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.Orders
    (
        OrderId             INT         IDENTITY(1,1)   NOT NULL,
        OrderNumber         NVARCHAR(20)                NOT NULL,  -- 'ORD001', 'OR62051', 'SBZ-8924-M'
        UserId              INT                             NULL,
        CustomerName        NVARCHAR(100)               NOT NULL,  -- snapshot, not Users.FullName
        CustomerEmail       NVARCHAR(256) COLLATE SQL_Latin1_General_CP1_CI_AS NOT NULL,
        CustomerPhone       NVARCHAR(16)                NOT NULL,  -- stored with formatting: '+91 9876543210'
        OrderDate           DATETIME2(0)                NOT NULL CONSTRAINT DF_Orders_Date DEFAULT (SYSUTCDATETIME()),  -- MISMATCH: code holds a string
        Status              NVARCHAR(20)                NOT NULL CONSTRAINT DF_Orders_Status DEFAULT (N'Pending'),
        PaymentMethodId     INT                         NOT NULL,
        DeliveryAddressId   INT                             NULL,  -- optional link to the source address
        DeliveryAddress     NVARCHAR(300)               NOT NULL,  -- flattened snapshot, as today
        DeliverySlot        NVARCHAR(10)                    NULL,  -- forced on the form, then discarded
        Subtotal            DECIMAL(10,2)               NOT NULL,
        DeliveryCharge      DECIMAL(10,2)               NOT NULL CONSTRAINT DF_Orders_Delivery DEFAULT (0),
        Discount            DECIMAL(10,2)               NOT NULL CONSTRAINT DF_Orders_Discount DEFAULT (0),  -- stored positive, subtracted at render
        TotalAmount         DECIMAL(10,2)               NOT NULL,
        CreatedDate         DATETIME2(0)                NOT NULL CONSTRAINT DF_Orders_Created DEFAULT (SYSUTCDATETIME()),
        ModifiedDate        DATETIME2(0)                    NULL,

        CONSTRAINT PK_Orders                    PRIMARY KEY CLUSTERED (OrderId),
        CONSTRAINT UQ_Orders_OrderNumber        UNIQUE (OrderNumber),
        CONSTRAINT FK_Orders_Users              FOREIGN KEY (UserId) REFERENCES dbo.Users (UserId),
        CONSTRAINT FK_Orders_PaymentMethods     FOREIGN KEY (PaymentMethodId) REFERENCES dbo.PaymentMethods (PaymentMethodId),
        CONSTRAINT FK_Orders_Addresses          FOREIGN KEY (DeliveryAddressId) REFERENCES dbo.Addresses (AddressId),
        -- The exact five literals in the Admin/Orders status dropdown.
        CONSTRAINT CK_Orders_Status             CHECK (Status IN (N'Pending', N'Confirmed', N'Out for Delivery', N'Delivered', N'Cancelled')),
        CONSTRAINT CK_Orders_Slot               CHECK (DeliverySlot IS NULL OR DeliverySlot IN (N'Morning', N'Evening')),
        CONSTRAINT CK_Orders_Money              CHECK (Subtotal >= 0 AND DeliveryCharge >= 0 AND Discount >= 0 AND TotalAmount >= 0),
        -- Verified against all four seeded orders: 1240, 850, 2100, 850.
        CONSTRAINT CK_Orders_TotalArithmetic    CHECK (TotalAmount = Subtotal + DeliveryCharge - Discount)
    );

    CREATE INDEX IX_Orders_CustomerEmail ON dbo.Orders (CustomerEmail) INCLUDE (OrderDate, Status, TotalAmount);
    CREATE INDEX IX_Orders_UserId        ON dbo.Orders (UserId);
    CREATE INDEX IX_Orders_OrderDate     ON dbo.Orders (OrderDate DESC) INCLUDE (Status);
END
GO

/* ---------------------------------------------------------------------------
   11. OrderItems
   Today this is a nested List<OrderItem> with no id and no parent key.

   ProductId is NULLABLE on purpose. OrderItem identifies its product by NAME
   string, and three of the fifteen distinct names in the seeded orders match
   no row in ProductRepository - a NOT NULL FK would reject existing data on
   day one. ProductName and Price stay as denormalised snapshots so an old
   invoice reprints at the price actually charged.

   LineNumber exists because both renderers print a running index
   (PdfInvoiceHelper.cs:104, Bill.aspx:284). Without it, invoices renumber.
   --------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.OrderItems', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.OrderItems
    (
        OrderItemId     INT             IDENTITY(1,1)   NOT NULL,
        OrderId         INT                             NOT NULL,
        LineNumber      INT                             NOT NULL,
        ProductId       INT                                 NULL,  -- see note above
        ProductName     NVARCHAR(100)                   NOT NULL,  -- historical snapshot
        Unit            NVARCHAR(10)                    NOT NULL,
        Quantity        INT                             NOT NULL,
        Price           DECIMAL(10,2)                   NOT NULL,  -- historical unit price charged

        CONSTRAINT PK_OrderItems            PRIMARY KEY CLUSTERED (OrderItemId),
