/* ---------------------------------------------------------------------------
   1. Categories
   Admin/Categories, AddCategory and EditCategory already exist as screens but
   persist nothing - their save handlers only redirect. Product.Category is a
   free string today, with five mutually inconsistent dropdown lists in markup.
   This table is the single source of truth those screens were written for.
   --------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.Categories', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.Categories
    (
        CategoryId      INT             IDENTITY(1,1)   NOT NULL,
        Name            NVARCHAR(50)                    NOT NULL,  -- AddCategory MaxLength=50, regex 2-50
        Description     NVARCHAR(200)                   NOT NULL,  -- MaxLength=200, regex ^[\s\S]{10,200}$
        Status          NVARCHAR(8)                     NOT NULL CONSTRAINT DF_Categories_Status DEFAULT (N'Active'),  -- rbStatusActive ternary
        CreatedDate     DATETIME2(0)                    NOT NULL CONSTRAINT DF_Categories_Created DEFAULT (SYSUTCDATETIME()),
        ModifiedDate    DATETIME2(0)                        NULL,

        CONSTRAINT PK_Categories        PRIMARY KEY CLUSTERED (CategoryId),
        CONSTRAINT UQ_Categories_Name   UNIQUE (Name),
        CONSTRAINT CK_Categories_Status CHECK (Status IN (N'Active', N'Inactive'))
    );
END
GO

