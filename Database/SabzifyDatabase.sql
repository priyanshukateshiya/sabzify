/* ---------------------------------------------------------------------------
   3. Users  (customers)
   AuthHelper.Users keyed by email. Email is the natural key the whole app uses;
   the surrogate UserId is added so child tables get a narrow, stable FK.

   Nullable columns are nullable for an evidenced reason, not for convenience:
     LastName      Register.aspx.cs:40 sets "" for a single-word name
     Pincode       Register.aspx never collects it - self-registered users have none
     AddressLine   write-only today; no screen ever reads it back
     ProfilePhoto  nothing is stored today, by path, filename or binary
   --------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.Users', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.Users
    (
        UserId              INT         IDENTITY(1,1)   NOT NULL,
        Email               NVARCHAR(256) COLLATE SQL_Latin1_General_CP1_CI_AS NOT NULL,
        PasswordHash        NVARCHAR(256)               NOT NULL,  -- MISMATCH: code stores plaintext
        PasswordSalt        NVARCHAR(64)                    NULL,
        FullName            NVARCHAR(100)               NOT NULL,  -- Register/AddUser MaxLength=100
        FirstName           NVARCHAR(50)                NOT NULL,  -- Profile MaxLength=50
        LastName            NVARCHAR(50)                    NULL,
        Mobile              NVARCHAR(10)                NOT NULL,  -- canonicalised to 10 digits, ^[6-9]\d{9}$
        AddressLine         NVARCHAR(250)                   NULL,  -- Register 250 vs AddUser 150; 250 is the floor
        City                NVARCHAR(50)                    NULL,
        [State]             NVARCHAR(50)                    NULL,
        Pincode             CHAR(6)                         NULL,  -- ^[1-9][0-9]{5}$ - text, never int
        ProfilePhotoPath    NVARCHAR(120)                   NULL,  -- relative path, matching Product.ImageUrl
        IsActive            BIT                         NOT NULL CONSTRAINT DF_Users_IsActive DEFAULT (1),
        CreatedDate         DATETIME2(0)                NOT NULL CONSTRAINT DF_Users_Created DEFAULT (SYSUTCDATETIME()),
        ModifiedDate        DATETIME2(0)                    NULL,

        CONSTRAINT PK_Users             PRIMARY KEY CLUSTERED (UserId),
        CONSTRAINT UQ_Users_Email       UNIQUE (Email),
        CONSTRAINT CK_Users_Mobile      CHECK (Mobile LIKE N'[6-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]'),
        CONSTRAINT CK_Users_Pincode     CHECK (Pincode IS NULL OR Pincode LIKE N'[1-9][0-9][0-9][0-9][0-9][0-9]')
    );
END
GO

