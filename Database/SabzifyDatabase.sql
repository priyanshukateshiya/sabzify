/* ---------------------------------------------------------------------------
   5. PasswordResetTokens
   The reset flow is the best-built thing in the project: 6 crypto-random
   digits, 10-minute expiry, 5-attempt cap, single-use, bound to a customer or
   an admin by a ForAdmin flag. But it lives in Session, so it is one per
   browser and gone on restart. This table makes it durable.

   No FK to Users/AdminUsers on purpose: the flow checks existence itself and
   must behave identically for an address that does not exist, so that the page
   cannot be used to discover which addresses are registered.
   --------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.PasswordResetTokens', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.PasswordResetTokens
    (
        TokenId         INT             IDENTITY(1,1)   NOT NULL,
        Email           NVARCHAR(256) COLLATE SQL_Latin1_General_CP1_CI_AS NOT NULL,
        Code            CHAR(6)                         NOT NULL,
        ForAdmin        BIT                             NOT NULL CONSTRAINT DF_PasswordResetTokens_Adm DEFAULT (0),
        ExpiresUtc      DATETIME2(0)                    NOT NULL,
        Attempts        INT                             NOT NULL CONSTRAINT DF_PasswordResetTokens_Att DEFAULT (0),
        IsVerified      BIT                             NOT NULL CONSTRAINT DF_PasswordResetTokens_Ver DEFAULT (0),
        IsUsed          BIT                             NOT NULL CONSTRAINT DF_PasswordResetTokens_Used DEFAULT (0),
        CreatedDate     DATETIME2(0)                    NOT NULL CONSTRAINT DF_PasswordResetTokens_Crt DEFAULT (SYSUTCDATETIME()),

        CONSTRAINT PK_PasswordResetTokens       PRIMARY KEY CLUSTERED (TokenId),
        CONSTRAINT CK_PasswordResetTokens_Code  CHECK (Code LIKE N'[0-9][0-9][0-9][0-9][0-9][0-9]'),
        CONSTRAINT CK_PasswordResetTokens_Att   CHECK (Attempts BETWEEN 0 AND 5)
    );

    CREATE INDEX IX_PasswordResetTokens_Lookup
        ON dbo.PasswordResetTokens (Email, ForAdmin, IsUsed) INCLUDE (ExpiresUtc);
END
GO

/* ---------------------------------------------------------------------------
   6. Products
   48 rows seeded in ProductRepository with contiguous ids 1-48; _lastId is
   primed to 48 and new ids come from Interlocked.Increment, so IDENTITY(49,1)
   reproduces that exactly with no collision.

   Name is deliberately NOT unique: 'Sweet Potato' is both Id 19 and Id 34.
   No code path deletes a product - there is no UI action and no repository
   method - so retirement is Status='Inactive' and child FKs must not cascade.
   --------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.Products', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.Products
    (
        ProductId       INT             IDENTITY(49,1)  NOT NULL,  -- seeds occupy 1-48
        Name            NVARCHAR(60)                    NOT NULL,  -- MaxLength=60; NOT unique
        CategoryId      INT                             NOT NULL,
        Price           DECIMAL(7,2)                    NOT NULL,  -- regex ^\d{1,5}(\.\d{1,2})?$
        OldPrice        DECIMAL(7,2)                        NULL CONSTRAINT DF_Products_OldPrice DEFAULT (NULL),  -- seed-only: no admin control exists
        Unit            NVARCHAR(2)                     NOT NULL,
        StockQuantity   INT                             NOT NULL CONSTRAINT DF_Products_Stock DEFAULT (0),
        ImageUrl        NVARCHAR(120)                   NOT NULL,  -- 'Content/Images/<name>.<ext>'
        IsOrganic       BIT                             NOT NULL CONSTRAINT DF_Products_Organic DEFAULT (0),
        IsSale          BIT                             NOT NULL CONSTRAINT DF_Products_Sale DEFAULT (0),  -- seed-only
        DiscountPercent TINYINT                         NOT NULL CONSTRAINT DF_Products_Discount DEFAULT (0),  -- seed-only
        Status          NVARCHAR(8)                     NOT NULL CONSTRAINT DF_Products_Status DEFAULT (N'Active'),
        Popularity      INT                             NOT NULL CONSTRAINT DF_Products_Popularity DEFAULT (80),  -- hardcoded 80 on every admin insert
        [Description]   NVARCHAR(300)                   NOT NULL,  -- regex ^[\s\S]{10,300}$
        CreatedDate     DATETIME2(0)                    NOT NULL CONSTRAINT DF_Products_Created DEFAULT (SYSUTCDATETIME()),
        ModifiedDate    DATETIME2(0)                        NULL,

        CONSTRAINT PK_Products              PRIMARY KEY CLUSTERED (ProductId),
        CONSTRAINT FK_Products_Categories   FOREIGN KEY (CategoryId) REFERENCES dbo.Categories (CategoryId),
        CONSTRAINT CK_Products_Price        CHECK (Price BETWEEN 1 AND 99999),
        CONSTRAINT CK_Products_OldPrice     CHECK (OldPrice IS NULL OR OldPrice BETWEEN 1 AND 99999),
        CONSTRAINT CK_Products_Unit         CHECK (Unit IN (N'KG', N'GM')),
        CONSTRAINT CK_Products_Stock        CHECK (StockQuantity BETWEEN 0 AND 99999),
        CONSTRAINT CK_Products_Status       CHECK (Status IN (N'Active', N'Inactive')),
        CONSTRAINT CK_Products_Discount     CHECK (DiscountPercent BETWEEN 0 AND 100),
        CONSTRAINT CK_Products_ImageUrl     CHECK (ImageUrl LIKE N'Content/Images/%.%')
    );

    CREATE INDEX IX_Products_CategoryId ON dbo.Products (CategoryId) INCLUDE (Status);
    CREATE INDEX IX_Products_Status     ON dbo.Products (Status) INCLUDE (Name, Price, Popularity);
END
GO

/* ---------------------------------------------------------------------------
   7. Addresses
   MISSING TABLE REQUIRED BY AN EXISTING FEATURE. AddAddress.aspx collects and
   validates 11 fields, then AddAddress.aspx.cs:18-23 discards every one and
   redirects to SavedAddresses.aspx, which renders two hardcoded cards.

   These columns are the form's own definitions. Note Building/Area/Landmark
   are separate here because AddAddress collects them separately - Checkout
   collapses them into one field, which is a mismatch to resolve in code.
   --------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.Addresses', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.Addresses
    (
        AddressId       INT             IDENTITY(1,1)   NOT NULL,
        UserId          INT                             NOT NULL,
        FullName        NVARCHAR(100)                   NOT NULL,  -- MaxLength=100
        CountryCode     NVARCHAR(4)                     NOT NULL CONSTRAINT DF_Addresses_Country DEFAULT (N'+91'),  -- ddlCode has one option: +91
        Phone           NVARCHAR(16)                    NOT NULL,  -- AddAddress 10; Checkout allows 16 with +91
        Building        NVARCHAR(150)                   NOT NULL,  -- regex ^.{3,150}$
        Area            NVARCHAR(150)                   NOT NULL,  -- regex ^.{3,150}$
        Landmark        NVARCHAR(100)                       NULL,  -- the only optional field on the form
        City            NVARCHAR(50)                    NOT NULL,
        [State]         NVARCHAR(50)                    NOT NULL,
        Pincode         CHAR(6)                         NOT NULL,
        AddressType     NVARCHAR(10)                    NOT NULL CONSTRAINT DF_Addresses_Type DEFAULT (N'Home'),  -- rbHome / rbOffice / rbOther
        IsDefault       BIT                             NOT NULL CONSTRAINT DF_Addresses_IsDefault DEFAULT (0),
        IsActive        BIT                             NOT NULL CONSTRAINT DF_Addresses_IsActive DEFAULT (1),
        CreatedDate     DATETIME2(0)                    NOT NULL CONSTRAINT DF_Addresses_Created DEFAULT (SYSUTCDATETIME()),
        ModifiedDate    DATETIME2(0)                        NULL,

        CONSTRAINT PK_Addresses             PRIMARY KEY CLUSTERED (AddressId),
        CONSTRAINT FK_Addresses_Users       FOREIGN KEY (UserId) REFERENCES dbo.Users (UserId) ON DELETE CASCADE,
        CONSTRAINT CK_Addresses_Type        CHECK (AddressType IN (N'Home', N'Office', N'Other')),
        CONSTRAINT CK_Addresses_Pincode     CHECK (Pincode LIKE N'[1-9][0-9][0-9][0-9][0-9][0-9]')
    );

    CREATE INDEX IX_Addresses_UserId ON dbo.Addresses (UserId) WHERE IsActive = 1;

    -- At most one default address per user. The rule exists today only in
    -- JavaScript on SavedAddresses.aspx; this enforces it in the database.
    CREATE UNIQUE INDEX UX_Addresses_OneDefaultPerUser
        ON dbo.Addresses (UserId) WHERE IsDefault = 1 AND IsActive = 1;
END
GO

