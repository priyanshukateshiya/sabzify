/* ============================================================================
   Sabzify - SQL Server database (schema + seed data in one file)
   ----------------------------------------------------------------------------
   This file is the combination of two scripts that were previously run in
   sequence:

       Database/SabzifySchema.sql    -> PART 1 below, the 14 tables
       Database/SabzifySeedData.sql  -> PART 2 below, the seed rows

   Nothing was added to or taken out of either one. Every CREATE TABLE, primary
   key, foreign key, constraint, index and INSERT is carried across verbatim,
   re-ordered only so that every dependency is created before it is needed.
   Running this one file is equivalent to running the two originals back to back.

   WHAT THIS SCRIPT DOES NOT DO
     - It does not CREATE, DROP or ALTER a database, and it does not name one.
       It only creates objects inside whatever database is current, so select
       the target database before executing (see HOW TO RUN).
     - It does not drop or alter an existing table and deletes nothing. Every
       table is guarded by IF OBJECT_ID(...) IS NULL and every seed block by
       IF NOT EXISTS (SELECT 1 FROM <table>), so the script is safe to re-run:
       a second run creates no object and inserts no row, and can never
       duplicate or modify a seed record.

   HOW TO RUN (SQL Server Management Studio)
     1. Connect to the server, then  File > Open > File...  (Ctrl+O) this file.
     2. Choose the target database in the toolbar dropdown - NOT master. If it
        does not exist yet, create it first in a separate query window:
            CREATE DATABASE Sabzify;
     3. Execute (F5).
     4. Expect in Messages:  'Sabzify schema created: 14 tables.' followed by
        'Sabzify seed data loaded.', and a five-row result grid:
            Products 48 | Users 3 | Orders 4 | OrderItems 26
            OrderItems unmatched 6   (expected - see the OrderItems note below)
     Leave SSMS at its default SET QUOTED_IDENTIFIER ON. The script also sets
     it ON itself in its first batch, so it completes under sqlcmd and OSQL
     too, which default it OFF. Later ad-hoc sessions are the catch: with it
     OFF, a statement whose plan touches one of the filtered indexes fails with
     Msg 8624, so pass -I to sqlcmd. See the SET note immediately below.

   PROVENANCE
     The schema is derived from the application code, not from an existing
     database: the project has no database today. All state lives in four
     static ConcurrentDictionary fields (AuthHelper.Users, AuthHelper.Admins,
     ProductRepository.Products, OrderRepository.Orders) plus three Session
     keys, and is lost on every app-domain recycle.

     Every column traces to code that reads or writes that value. Lengths come
     from the UI MaxLength attributes and validator regexes rather than from
     guesses; CHECK constraint values are the exact string literals the C#
     writes and compares, so a mismatch here silently breaks every insert.

     The PART 2 rows were GENERATED by parsing the C# seed sources, not typed
     by hand:
         ProductRepository.SeedProducts()  -> dbo.Products
         AuthHelper static constructor     -> dbo.Users, dbo.AdminUsers
         OrderRepository.SeedOrders()      -> dbo.Orders, dbo.OrderItems
     Re-generate them rather than editing them, so the two copies cannot drift.

     Passwords are NOT carried across. They are plaintext in AuthHelper.cs and
     this schema stores a hash, so every seeded account gets an unusable
     '!SET-ME!' placeholder: set a real password through the application before
     using any of these accounts. Do not paste the plaintext passwords here.

   Collation note: Email columns are forced to a case-insensitive collation to
   match AuthHelper's StringComparer.OrdinalIgnoreCase dictionaries. Without it,
   a server with a CS collation would let "A@x.com" and "a@x.com" both register.
   ============================================================================ */

SET NOCOUNT ON;
SET ANSI_NULLS ON;
/* QUOTED_IDENTIFIER must be ON, and not only to run this script.

   Two filtered indexes below - UX_Addresses_OneDefaultPerUser and
   IX_OrderItems_ProductId - cannot be CREATED with it OFF, and any statement
   whose plan has to touch them fails the same way afterwards. Measured: with
   it OFF, `DELETE FROM dbo.Products` returns

       Msg 8624 ... Internal Query Processor Error: the query processor could
       not produce a query plan

   because removing a product has to maintain IX_OrderItems_ProductId. With it
   ON the same DELETE succeeds.

   System.Data.SqlClient and Microsoft.Data.SqlClient both set it ON by default,
   so the application is unaffected. sqlcmd and OSQL default it OFF, so set it
   in any ad-hoc session against this database. */
SET QUOTED_IDENTIFIER ON;
GO

/* Target database. This script neither creates nor names one - pick it in the
   SSMS toolbar dropdown, or uncomment the two lines below and edit the name.

   USE Sabzify;
   GO                                                                        */

